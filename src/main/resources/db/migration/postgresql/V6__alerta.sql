-- Alertas de las macetas (entrega 2026-11-10). Una fila por episodio: se abre cuando aparece el problema y se
-- cierra (fin) cuando lleva un rato resuelto. «notificada» = cuándo se avisó por correo (null = todavía no).
CREATE TABLE alerta (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maceta_id   INTEGER      NOT NULL REFERENCES maceta (idmaceta) ON DELETE CASCADE,
    tipo        VARCHAR(30)  NOT NULL,
    nivel       VARCHAR(10)  NOT NULL,
    mensaje     VARCHAR(255) NOT NULL,
    inicio      TIMESTAMP    NOT NULL,
    vista       TIMESTAMP    NOT NULL,
    fin         TIMESTAMP,
    notificada  TIMESTAMP
);
-- Como mucho una alerta abierta por maceta y tipo: así no se repite la misma alerta en cada revisión.
CREATE UNIQUE INDEX ux_alerta_abierta ON alerta (maceta_id, tipo) WHERE fin IS NULL;
CREATE INDEX idx_alerta_maceta_inicio ON alerta (maceta_id, inicio);
