-- P-DB1: histórico de lecturas consultable por rangos (entrega 2026-11-06).
-- Sustituye a fechahora + fechahora_has_sensor (fecha troceada en VARCHAR y valor como texto), que se
-- mantienen solo porque SensorServiceImpl las usa para descartar lecturas repetidas en el mismo minuto.
-- maceta_id es NULL para los sensores que no están en una maceta (ultrasonidos del depósito).
CREATE TABLE lectura (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id INTEGER     NOT NULL REFERENCES sensor (idsensor) ON DELETE CASCADE,
    maceta_id INTEGER     REFERENCES maceta (idmaceta) ON DELETE CASCADE,
    magnitud  VARCHAR(20) NOT NULL,
    valor     REAL        NOT NULL,
    ts        TIMESTAMP   NOT NULL
);
-- Consulta típica: una magnitud de una maceta en un intervalo (métricas, gráficas).
CREATE INDEX idx_lectura_maceta_magnitud_ts ON lectura (maceta_id, magnitud, ts);
CREATE INDEX idx_lectura_sensor_ts ON lectura (sensor_id, ts);
