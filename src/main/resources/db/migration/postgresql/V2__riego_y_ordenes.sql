-- Riegos registrados por el ESP32 (entrega 2026-11-04, E7) y órdenes «Regar ahora» (entrega 2026-11-05).
-- Equivalen a db/mysql-antiguo/riego.sql y orden_riego.sql.
CREATE TABLE riego (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maceta_id       INTEGER     NOT NULL REFERENCES maceta (idmaceta) ON DELETE CASCADE,
    ts              TIMESTAMP   NOT NULL,
    duracion_ms     INTEGER     NOT NULL DEFAULT 0,
    pulsos          INTEGER     NOT NULL DEFAULT 0,
    humedad_antes   REAL,
    humedad_despues REAL,
    nivel_antes     REAL,
    nivel_despues   REAL,
    motivo          VARCHAR(10) NOT NULL DEFAULT 'AUTO',
    resultado       VARCHAR(20) NOT NULL DEFAULT 'OK'
);
CREATE INDEX idx_riego_maceta_ts ON riego (maceta_id, ts);

CREATE TABLE orden_riego (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maceta_id   INTEGER     NOT NULL REFERENCES maceta (idmaceta) ON DELETE CASCADE,
    solicitante VARCHAR(45),
    creada      TIMESTAMP   NOT NULL,
    entregada   TIMESTAMP,
    estado      VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE'
);
CREATE INDEX idx_orden_maceta_estado ON orden_riego (maceta_id, estado);
