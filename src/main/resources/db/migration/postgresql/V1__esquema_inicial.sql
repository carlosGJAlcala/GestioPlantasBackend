-- =====================================================================================
-- Esquema base del huerto en PostgreSQL (entrega mejora-codigo 2026-11-06).
-- Traducción del esquema MySQL original (huertodbdev) a partir de las entidades JPA.
--
-- Los nombres van SIN comillas: PostgreSQL los guarda en minúsculas y Hibernate (estrategia
-- PhysicalNamingStrategyStandardImpl, nombres sin comillas) los encuentra igual. No añadir comillas.
-- Hibernate arranca con ddl-auto=validate: si se cambia una entidad, crear una V<n> nueva, nunca
-- editar una migración ya aplicada (Flyway guarda su checksum).
-- =====================================================================================

-- ---------- Personas y roles ----------
CREATE TABLE persona (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(45),
    apellido          VARCHAR(45),
    usuario           VARCHAR(45) NOT NULL,
    correoelectronico VARCHAR(100),
    -- Hoy SHA-256 en hex (64 caracteres; en MySQL era VARCHAR(45) y se truncaba). 100 deja sitio para BCrypt (S2).
    passwordsha256    VARCHAR(100),
    dni               VARCHAR(45),
    role              VARCHAR(10) CHECK (role IN ('ADMIN', 'USER')),  -- NULL = USER (Persona#getAuthorities)
    CONSTRAINT uq_persona_usuario UNIQUE (usuario)
);

CREATE TABLE administrador (
    persona_id INTEGER PRIMARY KEY REFERENCES persona (id) ON DELETE CASCADE
);

CREATE TABLE usuario (
    persona_id               INTEGER PRIMARY KEY REFERENCES persona (id) ON DELETE CASCADE,
    administrador_persona_id INTEGER NOT NULL REFERENCES administrador (persona_id),
    fechadealta              TIMESTAMPTZ,
    fechabaja                TIMESTAMPTZ
);

-- ---------- Huertos y macetas ----------
-- idHuerto no es autoincremental en la entidad (lo asigna quien crea el huerto).
CREATE TABLE huerto (
    idhuerto      INTEGER PRIMARY KEY,
    numeromacetas INTEGER
);

CREATE TABLE huerto_has_usuario (
    huerto_idhuerto    INTEGER NOT NULL REFERENCES huerto (idhuerto) ON DELETE CASCADE,
    usuario_persona_id INTEGER NOT NULL REFERENCES usuario (persona_id) ON DELETE CASCADE,
    PRIMARY KEY (huerto_idhuerto, usuario_persona_id)
);

CREATE TABLE maceta (
    idmaceta                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    posicionmacetaenelhuerto VARCHAR(45),
    huerto_idhuerto          INTEGER REFERENCES huerto (idhuerto) ON DELETE CASCADE
);
CREATE INDEX idx_maceta_huerto ON maceta (huerto_idhuerto);

-- ---------- Sensores y depósito ----------
CREATE TABLE sensor (
    idsensor       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombresensor   VARCHAR(45),
    magnitudamedir VARCHAR(45),
    cantidadmedida VARCHAR(45),
    unidades       VARCHAR(45)
);

CREATE TABLE maceta_has_sensor (
    maceta_idmaceta INTEGER NOT NULL REFERENCES maceta (idmaceta) ON DELETE CASCADE,
    sensor_idsensor INTEGER NOT NULL REFERENCES sensor (idsensor) ON DELETE CASCADE,
    PRIMARY KEY (maceta_idmaceta, sensor_idsensor)
);
CREATE INDEX idx_mhs_sensor ON maceta_has_sensor (sensor_idsensor);

CREATE TABLE depositoagua (
    iddepositoagua  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidadmaxima  REAL,
    alturadeposito  REAL,
    estado          VARCHAR(45),
    sensor_idsensor INTEGER REFERENCES sensor (idsensor) ON DELETE SET NULL,
    huerto_idhuerto INTEGER NOT NULL REFERENCES huerto (idhuerto) ON DELETE CASCADE
);

-- ---------- Catálogo de plantas ----------
CREATE TABLE tipoplanta (
    idtipoplanta                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombreplanta                    VARCHAR(45),
    descripcion                     VARCHAR(1024),
    nivelhumedadnecesariominimo     REAL,
    nivelluxnecesariominimo         REAL,
    niveltemperaturanecesariominimo REAL,
    nivelhumedadnecesariomaximo     REAL,
    nivelluxnecesariomaximo         REAL,
    niveltemperaturanecesariomaximo REAL,
    estaciones                      VARCHAR(528),
    zonaorigen                      VARCHAR(45)
);

CREATE TABLE planta (
    idplanta                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombreplanta            VARCHAR(45),
    fechaplantacion         DATE,
    estado                  VARCHAR(45),
    nivelactualhumedad      REAL,
    nivelactualluminosidad  REAL,
    nivelactualtemperatura  REAL,
    tipoplanta_idtipoplanta INTEGER NOT NULL REFERENCES tipoplanta (idtipoplanta),
    maceta_idmaceta         INTEGER NOT NULL REFERENCES maceta (idmaceta) ON DELETE CASCADE
);
CREATE INDEX idx_planta_maceta ON planta (maceta_idmaceta);

-- ---------- Histórico antiguo (se mantiene mientras el código lo use; ver V3 «lectura») ----------
CREATE TABLE fechahora (
    idfecha INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anyio   VARCHAR(45),
    mes     VARCHAR(45),
    dia     VARCHAR(45),
    hora    VARCHAR(45),
    minuto  VARCHAR(45)
);
CREATE INDEX idx_fechahora_instante ON fechahora (anyio, mes, dia, hora, minuto);

CREATE TABLE fechahora_has_sensor (
    fechahora_idfecha  INTEGER NOT NULL REFERENCES fechahora (idfecha) ON DELETE CASCADE,
    sensor_idsensor    INTEGER NOT NULL REFERENCES sensor (idsensor) ON DELETE CASCADE,
    cantidadregistrada VARCHAR(45),
    PRIMARY KEY (fechahora_idfecha, sensor_idsensor)
);
